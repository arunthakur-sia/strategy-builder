// Wave 3 (Translation) data-flow definition, shared by the server engine and the client UI.
// Deliberately free of 'server-only' / 'use client' so both sides import the exact same rules.
//
// Source of truth: the "Wave 3 Functional Flow Diagram". Every arrow in it is an entry below. Ids that
// belong to Wave 2 ('shiftAgenda', 'optionsEval', 'vmv') resolve through assessment.wave2.agents; Wave 3's
// own agents live under assessment.wave3.agents.
//
//   0. Gate: Wave 2's Shift Agenda (and, when that optional step is on, Strategic Options) and V/M/V
//      ("Strategic Outcomes") must be approved before the Strategy Map can run.
//   1. Strategy Map      (strategyMap)    <- Shift Agenda, Strategic Options (optional), V/M/V
//   2. KPIs / Performance(kpis)           <- Strategy Map, Wave 1 internal-analysis conversations (the eight
//                                            pillar agents), optional finance document collection
//   3. Initiatives       (initiatives)    <- KPIs, Strategy Map, Shift Agenda, optional functional & operations document collection
//   4. Prioritisation    (prioritisation) <- Initiatives, Strategy Map, Shift Agenda, optional functional & operations document collection
//   The two optional collections are separate SiaGPT collections the reviewer uploads into
//   (assessment.wave3.financeCollectionId / functionalCollectionId), created lazily on first upload.
//   5. Dashboard (not a SiaGPT agent: generated by the report LLM as structured JSON) <- the full
//      conversations of 1-4 plus V/M/V. Approving it is the wave gate before Wave 4.

import { wave2SkippedIds, wave2OptionsEnabled, wave2SwotBEnabled, wave2DownstreamStarted } from './wave2Shared'

export const WAVE3_ORDER = ['strategyMap', 'kpis', 'initiatives', 'prioritisation'] as const
export type Wave3AgentId = typeof WAVE3_ORDER[number]

export const WAVE3_LABELS: Record<string, string> = {
  strategyMap: '1. Strategy Map — themes & objectives',
  kpis: '2. KPIs / Performance — KPIs, baselines & targets',
  initiatives: '3. Initiatives definition — action plans & roadmap',
  prioritisation: '4. Initiatives prioritisation',
}
export const WAVE3_DASHBOARD_LABEL = '5. Strategy Visualisation / BI Dashboard'

/** The optional Wave 3 document collections and which agents get each attached (the "(collection)" arrows). */
export type Wave3CollectionKind = 'finance' | 'functional'
export const WAVE3_COLLECTION_FIELDS: Record<Wave3CollectionKind, 'financeCollectionId' | 'functionalCollectionId'> = {
  finance: 'financeCollectionId', functional: 'functionalCollectionId',
}
export const WAVE3_USES_COLLECTION: Record<string, Wave3CollectionKind | null> = {
  strategyMap: null, kpis: 'finance', initiatives: 'functional', prioritisation: 'functional',
}

/** KPIs receive the Wave 1 internal-analysis conversations ("Baselines · Internal Analysis + finance"). */
export const WAVE3_USES_INTERNAL_ANALYSIS: Record<string, boolean> = {
  strategyMap: false, kpis: true, initiatives: false, prioritisation: false,
}

/** Every upstream agent output each agent consumes (diagram arrows). All must be approved before it runs. */
export const WAVE3_INPUTS: Record<string, string[]> = {
  strategyMap: ['shiftAgenda', 'optionsEval', 'vmv'],
  kpis: ['strategyMap'],
  initiatives: ['kpis', 'strategyMap', 'shiftAgenda'],
  prioritisation: ['initiatives', 'strategyMap', 'shiftAgenda'],
}

/** The dashboard is built from V/M/V (the direct "Strategic Outcomes" arrow) and all four Wave 3 agents. */
export const WAVE3_DASHBOARD_INPUTS: string[] = ['vmv', ...WAVE3_ORDER]

export function isWave3AgentId(id: string): boolean {
  return (WAVE3_ORDER as readonly string[]).includes(id)
}

/** Dependencies for one Wave 3 agent given the Wave 2 optional-step choices (a skipped Strategic Options
 *  step simply drops out of the Strategy Map's inputs, as in Wave 2). */
export function wave3DepIds(agentId: string, assessment: any): string[] {
  const skipped = wave2SkippedIds(wave2OptionsEnabled(assessment), wave2SwotBEnabled(assessment))
  return (WAVE3_INPUTS[agentId] || []).filter(id => !skipped.includes(id))
}

export function wave3Sequence(): string[] {
  return [...WAVE3_ORDER]
}

function agentOf(assessment: any, id: string): any {
  return isWave3AgentId(id) ? assessment.wave3?.agents?.[id] : assessment.wave2?.agents?.[id]
}

function approvedIn(assessment: any, id: string): boolean {
  const a = agentOf(assessment, id)
  return !!a && a.approvedVersion !== null && a.approvedVersion !== undefined
}

export function dashboardApproved(assessment: any): boolean {
  const d = assessment?.wave3?.dashboard
  return !!d && d.approvedVersion !== null && d.approvedVersion !== undefined
}

function started(a: any): boolean {
  return !!(a?.chatHistory?.length || a?.versionHistory?.length)
}

/** True once anything that consumes `id`'s approved output has started — another Wave 3 agent, or the
 *  dashboard (once generated or running) for the ids it is built from. Wave 2 ids are also checked here
 *  because Wave 3 consumes them; use downstreamStarted() for the combined answer. */
export function wave3DownstreamStarted(assessment: any, id: string): boolean {
  const w3 = assessment?.wave3
  if (!w3) return false
  const agents = w3.agents || {}
  const byAgent = Object.keys(agents).some(otherId =>
    otherId !== id && wave3DepIds(otherId, assessment).includes(id) && started(agents[otherId]))
  const dash = w3.dashboard
  const byDashboard = WAVE3_DASHBOARD_INPUTS.includes(id) && !!(dash?.data || dash?.status === 'in_progress')
  return byAgent || byDashboard
}

/** Combined gate for unlocking an approved agent of Wave 1's SWOT, Wave 2 or Wave 3. */
export function downstreamStarted(assessment: any, id: string): boolean {
  return wave2DownstreamStarted(assessment, id) || wave3DownstreamStarted(assessment, id)
}

/**
 * Moves untouched Wave 3 agents (and the dashboard) between 'locked' and 'not_started' as their upstream
 * approvals change. Re-derives depIds from the current Wave 2 optional-step choices on every call, so it is
 * safe to call from any route that can change an approval. Never touches a started agent, never auto-runs.
 */
export function recomputeWave3Locks(assessment: any) {
  const wave3 = assessment?.wave3
  if (!wave3?.agents) return
  const settle = (agent: any, depIds: string[]) => {
    if (!agent) return
    agent.depIds = depIds
    if (agent.status === 'in_progress') return
    const untouched = !started(agent) && !agent.data && (agent.approvedVersion === null || agent.approvedVersion === undefined)
    const depsDone = depIds.every(d => approvedIn(assessment, d))
    if (agent.status === 'locked' && depsDone) agent.status = 'not_started'
    else if (agent.status === 'not_started' && untouched && !depsDone) agent.status = 'locked'
  }
  for (const id of WAVE3_ORDER) settle(wave3.agents[id], wave3DepIds(id, assessment))
  settle(wave3.dashboard, WAVE3_DASHBOARD_INPUTS)
}
